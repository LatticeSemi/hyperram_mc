                sys_cache_ipgen_iob_ram_2p #(.DATA_W(FIFO_DATA_W),
                        .ADDR_W(FIFO_ADDR_W)) iob_ram_2p0 (.clk_i(clk), 
                            .w_en_i(mem_w_en), 
                            .w_addr_i(mem_w_addr), 
                            .w_data_i(mem_w_data), 
                            .r_en_i(mem_r_en), 
                            .r_addr_i(mem_r_addr), 
                            .r_data_o(mem_r_data)) ; /*-ramstyle block_ram */
                sys_cache_ipgen_iob_fifo_sync #(.R_DATA_W(FIFO_DATA_W),
                        .W_DATA_W(FIFO_DATA_W),
                        .ADDR_W(FIFO_ADDR_W)) write_throught_buffer (.clk_i(clk), 
                            .rst_i(reset), 
                            .arst_i(reset), 
                            .ext_mem_w_en_o(mem_w_en), 
                            .ext_mem_w_addr_o(mem_w_addr), 
                            .ext_mem_w_data_o(mem_w_data), 
                            .ext_mem_r_en_o(mem_r_en), 
                            .ext_mem_r_addr_o(mem_r_addr), 
                            .ext_mem_r_data_i(mem_r_data), 
                            .level_o(), 
                            .r_data_o(buffer_dout), 
                            .r_empty_o(buffer_empty), 
                            .r_en_i(write_ready), 
                            .w_data_i({addr_reg,
                                wdata_reg,
                                wstrb_reg}), 
                            .w_full_o(buffer_full), 
                            .w_en_i((write_access & ready))) ; 
                //buffer status
                assign wtbuf_full = buffer_full ; 
                assign wtbuf_empty = ((buffer_empty & write_ready) & (~write_valid)) ; 
                //back-end write channel
                assign write_valid = (~buffer_empty) ; 
                assign write_addr = buffer_dout[(FE_NBYTES + FE_DATA_W) +: (FE_ADDR_W - FE_BYTE_W)] ; 
                assign write_wdata = buffer_dout[FE_NBYTES +: FE_DATA_W] ; 
                assign write_wstrb = buffer_dout[0 +: FE_NBYTES] ; 
                //back-end read channel
                assign replace_valid = ((((~hit) & read_access) & (~replace)) & (buffer_empty & write_ready)) ; 
                assign replace_addr = addr[(FE_ADDR_W - 1):(BE_BYTE_W + LINE2MEM_W)] ; 
            end
        else
            begin : genblk1
                // if (WRITE_POL == WRITE_BACK)
                //back-end write channel
                assign write_wstrb = {FE_NBYTES{1'bx}} ; 
                //write_valid, write_addr and write_wdata assigns are generated bellow (dependencies)
                //back-end read channel
                assign replace_valid = ((((~|way_hit) & write_ready) & valid_reg) & (~replace)) ; 
                assign replace_addr = addr[(FE_ADDR_W - 1):(BE_BYTE_W + LINE2MEM_W)] ; 
                //buffer status (non-existant)
                assign wtbuf_full = 1'b0 ; 
                assign wtbuf_empty = 1'b1 ; 
            end
    endgenerate
    //////////////////////////////////////////////////////
    // Read-After-Write (RAW) Hazard (pipeline) control
    //////////////////////////////////////////////////////
    wire raw ; 
    reg write_hit_prev ; 
    reg [(WORD_OFF_W - 1):0] offset_prev ; 
    reg [(N_WAYS - 1):0] way_hit_prev ; 
    generate
        if ((WRITE_POL == 0)) 
            begin : genblk2
                always
                    @(posedge clk)
                    begin
                        write_hit_prev <=  (write_access & (|way_hit)) ;
                        //previous write position
                        offset_prev <=  offset ;
                        way_hit_prev <=  way_hit ;
                    end
                assign raw = ((write_hit_prev & (way_hit_prev == way_hit)) & (offset_prev == offset)) ; 
            end
        else
            begin : genblk2
                //// if (WRITE_POL == WRITE_BACK)
                always
                    @(posedge clk)
                    begin
                        write_hit_prev <=  write_access ;//all writes will have the data in cache in the end
                        //previous write position
                        offset_prev <=  offset ;
                        way_hit_prev <=  way_hit ;
                    end
                assign raw = (((write_hit_prev & (way_hit_prev == way_hit)) & (offset_prev == offset)) & read_access) ; //without read_access it is an infinite replacement loop
            end
    endgenerate
    ///////////////////////////////////////////////////////////////
    // Hit signal: data available and in the memory's output
    ///////////////////////////////////////////////////////////////
    assign hit = (((|way_hit) & (~replace)) & (~raw)) ; 
    /////////////////////////////////
    //front-end READY signal
    /////////////////////////////////
    generate
        if ((WRITE_POL == 0)) 
            begin: genblk3
                assign ready = ((hit & read_access) | ((~buffer_full) & write_access)) ; 
            end
        else
            begin: genblk3
                // if (WRITE_POL == WRITE_BACK)
                assign ready = (hit & valid_reg) ; 
            end
    endgenerate
    //cache-control hit-miss counters enables
    generate
        if ((CTRL_CACHE & CTRL_CNT)) 
            begin : genblk4
                //cache-control hit-miss counters enables
                assign write_hit = (ready & (hit & write_access)) ; 
                assign write_miss = (ready & ((~hit) & write_access)) ; 
                assign read_hit = (ready & (hit & read_access)) ; 
                assign read_miss = replace_valid ; //will also subtract read_hit
            end
        else
            begin : genblk4
                assign write_hit = 1'bx ; 
                assign write_miss = 1'bx ; 
                assign read_hit = 1'bx ; 
                assign read_miss = 1'bx ; 
            end
    endgenerate
    ////////////////////////////////////////
    //Memories implementation configurations
    ////////////////////////////////////////
    genvar i, 
        j, 
        k ; 
    generate
        //Data-Memory
        for (k = 0;(k < N_WAYS);k = (k + 1))
        begin : n_ways_block
            for (j = 0;(j < (2 ** LINE2MEM_W));j = (j + 1))
            begin : line2mem_block
                for (i = 0;(i < (BE_DATA_W / FE_DATA_W));i = (i + 1))
                begin : BE_FE_block
                    sys_cache_ipgen_iob_gen_sp_ram #(.DATA_W(FE_DATA_W),
                            .ADDR_W(LINE_OFF_W)) cache_memory (.clk(clk), 
                                .en(valid), 
                                .we(({FE_NBYTES{way_hit[k]}} & line_wstrb[(((j * (BE_DATA_W / FE_DATA_W)) + i) * FE_NBYTES) +: FE_NBYTES])), 
                                .addr((((write_access & way_hit[k]) & (((j * (BE_DATA_W / FE_DATA_W)) + i) == offset)) ? index_reg : index)), 
                                .data_in((replace ? read_rdata[(i * FE_DATA_W) +: FE_DATA_W] : wdata_reg)), 
                                .data_out(line_rdata[((((k * (2 ** WORD_OFF_W)) + (j * (BE_DATA_W / FE_DATA_W))) + i) * FE_DATA_W) +: FE_DATA_W])) ; /*-ramstyle block_ram */
                end
            end
        end
        //Cache Line Write Strobe
        if ((LINE2MEM_W > 0)) 
            begin : genblk6
                always
                    @(*)
                    if (replace) 
                        line_wstrb = ({BE_NBYTES{read_valid}} << (read_addr * BE_NBYTES)) ;
                    else
                        //line-replacement: read_addr indexes the words in cache-line
                        line_wstrb = ((wstrb_reg & {FE_NBYTES{write_access}}) << (offset * FE_NBYTES)) ;
            end
        else
            begin : genblk6
                always
                    @(*)
                    if (replace) 
                        line_wstrb = {BE_NBYTES{read_valid}} ;
                    else
                        //line-replacement: mem's word replaces entire line
                        line_wstrb = ((wstrb_reg & {FE_NBYTES{write_access}}) << (offset * FE_NBYTES)) ;
            end
        // Valid-Tag memories & replacement-policy
        if ((N_WAYS > 1)) 
            begin : genblk7
                wire [(NWAY_W - 1):0] way_hit_bin, 
                    way_select_bin ; //reason for the 2 generates for single vs multiple ways
                //valid-memory
                always
                    @(posedge clk or 
                        posedge reset)
                    begin
                        if (reset) 
                            v_reg <=  0 ;
                        else
                            if (invalidate) 
                                v_reg <=  0 ;
                            else
                                if (replace_valid) 
                                    v_reg <=  (v_reg | (1 << ((way_select_bin * (2 ** LINE_OFF_W)) + index_reg))) ;
                                else
                                    v_reg <=  v_reg ;
                    end
                for (k = 0;(k < N_WAYS);k = (k + 1))
                begin : tag_mem_block
                    //valid-memory output stage register - 1 c.c. read-latency (cleaner simulation during rep.)
                    always
                        @(posedge clk)
                        if (invalidate) 
                            v[k] <=  0 ;
                        else
                            v[k] <=  v_reg[(((2 ** LINE_OFF_W) * k) + index)] ;
                    //tag-memory
                    sys_cache_ipgen_iob_ram_sp #(.DATA_W(TAG_W),
                            .ADDR_W(LINE_OFF_W)) tag_memory (.clk_i(clk), 
                                .en_i(valid), 
                                .we_i((way_select[k] & replace_valid)), 
                                .addr_i(index), 
                                .d_i(tag), 
                                .d_o(line_tag[(TAG_W * k) +: TAG_W])) ; /*-ramstyle block_ram */
                    //Way hit signal - hit or replacement
                    assign way_hit[k] = ((tag == line_tag[(TAG_W * k) +: TAG_W]) & v[k]) ; 
                end
                //Read Data Multiplexer
                assign rdata[(FE_DATA_W - 1):0] = (line_rdata >> (FE_DATA_W * (offset + ((2 ** WORD_OFF_W) * way_hit_bin)))) ; 
                //replacement-policy module
                sys_cache_ipgen_replacement_policy #(.N_WAYS(N_WAYS),
                        .LINE_OFF_W(LINE_OFF_W),
                        .REP_POLICY(REP_POLICY)) replacement_policy_algorithm (.clk(clk), 
                            .reset((reset | invalidate)), 
                            .write_en(ready), 
                            .way_hit(way_hit), 
                            .line_addr(index_reg), 
                            .way_select(way_select), 
                            .way_select_bin(way_select_bin)) ; 
                //onehot-to-binary for way-hit
                sys_cache_ipgen_onehot_to_bin #(.BIN_W(NWAY_W)) way_hit_encoder (.onehot(way_hit[(N_WAYS - 1):1]), 
                            .bin(way_hit_bin)) ; 
                //dirty-memory
                if ((WRITE_POL == 1)) 
                    begin : genblk2
                        always
                            @(posedge clk or 
                                posedge reset)
                            begin
                                if (reset) 
                                    dirty_reg <=  0 ;
                                else
                                    if (write_valid) 
                                        dirty_reg <=  (dirty_reg & (~(1 << ((way_select_bin * (2 ** LINE_OFF_W)) + index_reg)))) ;
                                    else
                                        // updates position with 0
                                        if ((write_access & hit)) 
                                            dirty_reg <=  (dirty_reg | (1 << ((way_hit_bin * (2 ** LINE_OFF_W)) + index_reg))) ;
                                        else
                                            //updates position with 1
                                            dirty_reg <=  dirty_reg ;
                            end
                        for (k = 0;(k < N_WAYS);k = (k + 1))
                        begin : dirty_block
                            //valid-memory output stage register - 1 c.c. read-latency (cleaner simulation during rep.)
                            always
                                @(posedge clk)
                                dirty[k] <=  dirty_reg[(((2 ** LINE_OFF_W) * k) + index)] ;
                        end
                        //flush line
                        assign write_valid = ((valid_reg & (~(|way_hit))) & (way_select == dirty)) ; //flush if there is not a hit, and the way selected is dirty
                        wire [(TAG_W - 1):0] tag_flush = (line_tag >> (way_select_bin * TAG_W)) ; //auxiliary wire
                        assign write_addr = {tag_flush,
                                    index_reg} ; //the position of the current block in cache (not of the access)
                        assign write_wdata = (line_rdata >> ((way_select_bin * FE_DATA_W) * (2 ** WORD_OFF_W))) ; 
                    end
            end
        else
            begin : genblk7
                //valid-memory
                always
                    @(posedge clk or 
                        posedge reset)
                    begin
                        if (reset) 
                            v_reg <=  0 ;
                        else
                            if (invalidate) 
                                v_reg <=  0 ;
                            else
                                if (replace_valid) 
                                    v_reg <=  (v_reg | (1 << index)) ;
                                else
                                    v_reg <=  v_reg ;
                    end
                //valid-memory output stage register - 1 c.c. read-latency (cleaner simulation during rep.)
                always
                    @(posedge clk)
                    if (invalidate) 
                        v <=  0 ;
                    else
                        v <=  v_reg[index] ;
                //tag-memory
                sys_cache_ipgen_iob_ram_sp #(.DATA_W(TAG_W),
                        .ADDR_W(LINE_OFF_W)) tag_memory (.clk_i(clk), 
                            .en_i(valid), 
                            .we_i(replace_valid), 
                            .addr_i(index), 
                            .d_i(tag), 
                            .d_o(line_tag)) ; /*-ramstyle block_ram */
                //Cache hit signal that indicates which way has had the hit (also during replacement)
                assign way_hit = ((tag == line_tag) & v) ; 
                //Read Data Multiplexer
                assign rdata[(FE_DATA_W - 1):0] = (line_rdata >> (FE_DATA_W * offset)) ; 
                //dirty-memory
                if ((WRITE_POL == 1)) 
                    begin : genblk1
                        //dirty-memory
                        always
                            @(posedge clk or 
                                posedge reset)
                            begin
                                if (reset) 
                                    dirty_reg <=  0 ;
                                else
                                    if (write_valid) 
                                        dirty_reg <=  (dirty_reg & (~(1 << index_reg))) ;
                                    else
                                        //updates postion with 0
                                        if ((write_access & hit)) 
                                            dirty_reg <=  (dirty_reg | (1 << index_reg)) ;
                                        else
                                            //updates position with 1 (needs to be index_reg otherwise updates the new index if the previous access was a write)
                                            dirty_reg <=  dirty_reg ;
                            end
                        always
                            @(posedge clk)
                            dirty <=  dirty_reg[index] ;
                        //flush line
                        assign write_valid = ((write_access & (~way_hit)) & dirty) ; //flush if there is not a hit, and is dirty
                        assign write_addr = {line_tag,
                                    index} ; //the position of the current block in cache (not of the access)
                        assign write_wdata = line_rdata ; 
                    end
            end
    endgenerate

// cache_memory
endmodule



