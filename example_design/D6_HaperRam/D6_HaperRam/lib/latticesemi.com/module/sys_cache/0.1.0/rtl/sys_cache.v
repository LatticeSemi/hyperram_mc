`timescale 1ns/1ps
//Address-port
//Control-ports
//Replacement Policy
//Write Policy
//Cache-Control
//Addresses for cache controller's task
module sys_cache_ipgen_write_channel_axi #(parameter FE_ADDR_W = 32, 
        parameter FE_DATA_W = 32, 
        parameter FE_NBYTES = (FE_DATA_W / 8), 
        parameter FE_BYTE_W = $clog2(FE_NBYTES), 
        parameter BE_ADDR_W = FE_ADDR_W, 
        parameter BE_DATA_W = FE_DATA_W, 
        parameter BE_NBYTES = (BE_DATA_W / 8), 
        parameter BE_BYTE_W = $clog2(BE_NBYTES), 
        parameter AXI_ADDR_W = BE_ADDR_W, 
        parameter AXI_DATA_W = BE_DATA_W, 
        parameter AXI_LEN_W = 8, 
        parameter AXI_ID_W = 1, 
        parameter [(AXI_ID_W - 1):0] AXI_ID = 0, 
        parameter WRITE_POL = 0, 
        parameter WORD_OFF_W = 3, 
        parameter LINE2MEM_W = (WORD_OFF_W - $clog2((BE_DATA_W / FE_DATA_W)))) (
    //AXI ID burst length (log2)
    // Write-Policy
    //write policy: write-through (0), write-back (1)
    //required for write-back
    //burst offset based on the cache and memory word size
    //IOb slave frontend interface    
    input valid, 
    input [(FE_ADDR_W - 1):(FE_BYTE_W + (WRITE_POL * WORD_OFF_W))] addr, 
    input [((FE_DATA_W + (WRITE_POL * ((FE_DATA_W * (2 ** WORD_OFF_W)) - FE_DATA_W))) - 1):0] wdata, 
    input [(FE_NBYTES - 1):0] wstrb, 
    output reg ready, 
    //AXI master backend interface 
    //  `include "m_axi_m_write_port.vh"
    output wire m_axi_awid, 
    output wire [31:0] m_axi_awaddr, 
    output wire [7:0] m_axi_awlen, 
    output wire [2:0] m_axi_awsize, 
    output wire [1:0] m_axi_awburst, 
    output wire m_axi_awlock, 
    output wire [3:0] m_axi_awcache, 
    output wire [2:0] m_axi_awprot, 
    output wire [3:0] m_axi_awqos, 
    output wire [3:0] m_axi_awregion, 
    output wire m_axi_awuser, 
    output wire m_axi_awvalid, 
    input wire m_axi_awready, 
    output wire [31:0] m_axi_wdata, 
    output wire [3:0] m_axi_wstrb, 
    output wire m_axi_wlast, 
    output wire m_axi_wuser, 
    output wire m_axi_wvalid, 
    input wire m_axi_wready, 
    input wire m_axi_bid, 
    input wire [1:0] m_axi_bresp, 
    input wire m_axi_buser, 
    input wire m_axi_bvalid, 
    output wire m_axi_bready, 
    input clk, 
    input reset) ;
    reg m_axi_awvalid_int ; 
    reg m_axi_wvalid_int ; 
    reg m_axi_bready_int ; 
    assign m_axi_awvalid = m_axi_awvalid_int ; 
    assign m_axi_wvalid = m_axi_wvalid_int ; 
    assign m_axi_bready = m_axi_bready_int ; 
    genvar i ; 
    generate
        if ((WRITE_POL == 0)) 
            begin : genblk1
                //Constant AXI signals
                assign m_axi_awid = AXI_ID ; 
                assign m_axi_awlen = 8'd0 ; 
                assign m_axi_awsize = BE_BYTE_W ; // verify - Writes data of the size of BE_DATA_W
                assign m_axi_awburst = 2'd0 ; 
                assign m_axi_awlock = 1'b0 ; // 00 - Normal Access
                assign m_axi_awcache = 4'b0011 ; 
                assign m_axi_awprot = 3'd0 ; 
                assign m_axi_wlast = m_axi_wvalid_int ; 
                //AXI Buffer Output signals
                assign m_axi_awaddr = ({BE_ADDR_W{1'b0}} + {addr[(FE_ADDR_W - 1):BE_BYTE_W],
                            {BE_BYTE_W{1'b0}}}) ; 
                if ((BE_DATA_W == FE_DATA_W)) 
                    begin : genblk1
                        assign m_axi_wstrb = wstrb ; 
                        assign m_axi_wdata = wdata ; 
                    end
                else
                    begin : genblk1
                        wire [((BE_BYTE_W - FE_BYTE_W) - 1):0] word_align = addr[FE_BYTE_W +: (BE_BYTE_W - FE_BYTE_W)] ; 
                        assign m_axi_wstrb = (wstrb << (word_align * FE_NBYTES)) ; 
                        for (i = 0;(i < (BE_DATA_W / FE_DATA_W));i = (i + 1))
                        begin : wdata_block
                            assign m_axi_wdata[(((i + 1) * FE_DATA_W) - 1):(i * FE_DATA_W)] = wdata ; 
                        end
                    end
                localparam idle = 2'd0, 
                    address = 2'd1, 
                    write = 2'd2, 
                    verif = 2'd3 ; 
                reg [1:0] state ; 
                always
                    @(posedge clk or 
                        posedge reset)
                    begin
                        if (reset) 
                            state <=  idle ;
                        else
                            case (state)
                            idle : 
                                begin
                                    if (valid) 
                                        state <=  address ;
                                    else
                                        state <=  idle ;
                                end
                            address : 
                                begin
                                    if (m_axi_awready) 
                                        state <=  write ;
                                    else
                                        state <=  address ;
                                end
                            write : 
                                begin
                                    if (m_axi_wready) 
                                        state <=  verif ;
                                    else
                                        state <=  write ;
                                end
                            default : 
                                //verif: begin //needs to be after the last word has been written, so this can't be optim
                                begin
                                    if (((m_axi_bvalid & (m_axi_bresp == 2'b00)) & (~valid))) 
                                        state <=  idle ;
                                    else
                                        //no more words to write
                                        if (((m_axi_bvalid & (m_axi_bresp == 2'b00)) & valid)) 
                                            state <=  address ;
                                        else
                                            //buffer still isn't empty
                                            if ((m_axi_bvalid & (~(m_axi_bresp == 2'b00)))) 
                                                //error
                                                state <=  address ;
                                            else
                                                //goes back to transfer the same data.
                                                state <=  verif ;
                                end
                            endcase 
                    end// always @ (posedge clk, posedge reset)
                always
                    @(*)
                    begin
                        ready = 1'b0 ;
                        m_axi_awvalid_int = 1'b0 ;
                        m_axi_wvalid_int = 1'b0 ;
                        m_axi_bready_int = 1'b0 ;
                        case (state)
                        idle : 
                            ready = 1'b1 ;
                        address : 
                            m_axi_awvalid_int = 1'b1 ;
                        write : 
                            m_axi_wvalid_int = 1'b1 ;
                        default : 
                            //verif:
                            begin
                                m_axi_bready_int = 1'b1 ;
                                ready = (m_axi_bvalid & (~(|m_axi_bresp))) ;
                            end
                        endcase 
                    end
            end
        else
            begin : genblk1
                // if (WRITE_POL == `WRITE_BACK)
                if ((LINE2MEM_W > 0)) 
                    begin : genblk1
                        //Constant AXI signals
                        assign m_axi_awid = AXI_ID ; 
                        assign m_axi_awlock = 1'b0 ; 
                        assign m_axi_awcache = 4'b0011 ; 
                        assign m_axi_awprot = 3'd0 ; 
                        //Burst parameters
                        assign m_axi_awlen = ((2 ** LINE2MEM_W) - 1) ; //will choose the burst lenght depending on the cache's and slave's data width
                        assign m_axi_awsize = BE_BYTE_W ; //each word will be the width of the memory for maximum bandwidth
                        assign m_axi_awburst = 2'b01 ; //incremental burst
                        //memory address
                        assign m_axi_awaddr = ({BE_ADDR_W{1'b0}} + {addr,
                                    {(FE_BYTE_W + WORD_OFF_W){1'b0}}}) ; //base address for the burst, with width extension
                        // memory write-data
                        reg [(LINE2MEM_W - 1):0] word_counter ; 
                        assign m_axi_wdata = (wdata >> (word_counter * BE_DATA_W)) ; 
                        assign m_axi_wstrb = {BE_NBYTES{1'b1}} ; 
                        assign m_axi_wlast = (&word_counter) ; 
                        localparam idle = 2'd0, 
                            address = 2'd1, 
                            write = 2'd2, 
                            verif = 2'd3 ; 
                        reg [1:0] state ; 
                        always
                            @(posedge clk or 
                                posedge reset)
                            begin
                                if (reset) 
                                    begin
                                        state <=  idle ;
                                        word_counter <=  0 ;
                                    end
                                else
                                    begin
                                        word_counter <=  0 ;
                                        //still waiting for response
                                        case (state)
                                        idle : 
                                            if (valid) 
                                                state <=  address ;
                                            else
                                                state <=  idle ;
                                        address : 
                                            if (m_axi_awready) 
                                                state <=  write ;
                                            else
                                                state <=  address ;
                                        write : 
                                            if ((m_axi_wready & (&word_counter))) 
                                                //last word written
                                                state <=  verif ;
                                            else
                                                if ((m_axi_wready & (~(&word_counter)))) 
                                                    begin
                                                        //word still available
                                                        state <=  write ;
                                                        word_counter <=  (word_counter + 1) ;
                                                    end
                                                else
                                                    begin
                                                        //waiting for handshake
                                                        state <=  write ;
                                                        word_counter <=  word_counter ;
                                                    end
                                        verif : 
                                            if ((m_axi_bvalid & (m_axi_bresp == 2'b00))) 
                                                state <=  idle ;
                                            else
                                                // write transfer completed
                                                if ((m_axi_bvalid & (~(m_axi_bresp == 2'b00)))) 
                                                    state <=  address ;
                                                else
                                                    // error, requires re-transfer
                                                    state <=  verif ;
                                        default : 
                                            ; 
                                        endcase 
                                    end// else: !if(reset)
                            end// always @ (posedge clk, posedge reset)
                        always
                            @(*)
                            begin
                                ready = 1'b0 ;
                                m_axi_awvalid_int = 1'b0 ;
                                m_axi_wvalid_int = 1'b0 ;
                                m_axi_bready_int = 1'b0 ;
                                case (state)
                                idle : 
                                    ready = (~valid) ;
                                address : 
                                    m_axi_awvalid_int = 1'b1 ;
                                write : 
                                    m_axi_wvalid_int = 1'b1 ;
                                default : 
                                    //verif:
                                    begin
                                        m_axi_bready_int = 1'b1 ;
                                        ready = (m_axi_bvalid & (~(|m_axi_bresp))) ;
                                    end
                                endcase 
                            end// always @ *
                    end
                else
                    begin : genblk1
                        // if (LINE2MEM_W == 0)
                        //Constant AXI signals
                        assign m_axi_awid = AXI_ID ; 
                        assign m_axi_awlock = 1'b0 ; 
                        assign m_axi_awcache = 4'b0011 ; 
                        assign m_axi_awprot = 3'd0 ; 
                        //Burst parameters - single
                        assign m_axi_awlen = 8'd0 ; //A single burst of Memory data width word
                        assign m_axi_awsize = BE_BYTE_W ; //each word will be the width of the memory for maximum bandwidth
                        assign m_axi_awburst = 2'b00 ; 
                        //memory address
                        assign m_axi_awaddr = ({BE_ADDR_W{1'b0}} + {addr,
                                    {BE_BYTE_W{1'b0}}}) ; //base address for the burst, with width extension
                        //memory write-data
                        assign m_axi_wdata = wdata ; 
                        assign m_axi_wstrb = {BE_NBYTES{1'b1}} ; //uses entire bandwidth
                        assign m_axi_wlast = m_axi_wvalid ; 
                        localparam idle = 2'd0, 
                            address = 2'd1, 
                            write = 2'd2, 
                            verif = 2'd3 ; 
                        reg [1:0] state ; 
                        always
                            @(posedge clk or 
                                posedge reset)
                            begin
                                if (reset) 
                                    state <=  idle ;
                                else
                                    //still waiting for response
                                    case (state)
                                    idle : 
                                        if (valid) 
                                            state <=  address ;
                                        else
                                            state <=  idle ;
                                    address : 
                                        if (m_axi_awready) 
                                            state <=  write ;
                                        else
                                            state <=  address ;
                                    write : 
                                        if (m_axi_wready) 
                                            state <=  verif ;
                                        else
                                            state <=  write ;
                                    default : 
                                        //verif:
                                        if ((m_axi_bvalid & (m_axi_bresp == 2'b00))) 
                                            state <=  idle ;
                                        else
                                            // write transfer completed
                                            if ((m_axi_bvalid & (~(m_axi_bresp == 2'b00)))) 
                                                state <=  address ;
                                            else
                                                // error, requires re-transfer
                                                state <=  verif ;
                                    endcase 
                            end
                        always
                            @(*)
                            begin
                                ready = 1'b0 ;
                                m_axi_awvalid_int = 1'b0 ;
                                m_axi_wvalid_int = 1'b0 ;
                                m_axi_bready_int = 1'b0 ;
                                case (state)
                                idle : 
                                    ready = (~valid) ;
                                address : 
                                    m_axi_awvalid_int = 1'b1 ;
                                write : 
                                    m_axi_wvalid_int = 1'b1 ;
                                default : 
                                    //verif:
                                    begin
                                        m_axi_bready_int = 1'b1 ;
                                        ready = (m_axi_bvalid & (~(|m_axi_bresp))) ;
                                    end
                                endcase 
                            end// always @ *
                    end
            end
    endgenerate
endmodule


