                        start_trans <=  1'b1 ;
                        trans_wr <=  local_wr ;
                        trans_size <=  (10'd1 << local_size) ;
                        //bit 47: 0 for write; bit 46: 0 for memory space; bit 45: 1 for linear burst
                        //bits 44:16: Row & Upper Column Address; bit 15:3: reserved; bit 2:0: Lower Column Address
                        cmd_addr <=  {(~local_wr),
                                1'b0,
                                1'b1,
                                2'b00,
