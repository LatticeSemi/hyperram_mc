        @(posedge S_AXI_ACLK)
        if (i_reset) 
            axil_bvalid <=  0 ;
        else
            if (axil_write_ready) 
                axil_bvalid <=  1 ;
            else
                if (S_AXI_BREADY) 
                    axil_bvalid <=  0 ;
    assign S_AXI_BVALID = axil_bvalid ; 
    assign S_AXI_BRESP = 2'b00 ; 
    // Read signaling
    generate
        if (OPT_SKIDBUFFER) 
            begin : SKIDBUFFER_READ
                wire arskd_valid ; 
                hram_controller0_ipgen_skidbuffer #(.OPT_OUTREG(0),
                        .OPT_LOWPOWER(OPT_LOWPOWER),
                        .DW((C_AXI_ADDR_WIDTH - ADDRLSB))) axilarskid (//
                        .i_clk(S_AXI_ACLK), 
                            .i_reset(i_reset), 
                            .i_valid(S_AXI_ARVALID), 
                            .o_ready(S_AXI_ARREADY), 
                            .i_data(S_AXI_ARADDR[(C_AXI_ADDR_WIDTH - 1):ADDRLSB]), 
                            .o_valid(arskd_valid), 
                            .i_ready(axil_read_ready), 
                            .o_data(arskd_addr)) ; 
                assign axil_read_ready = (arskd_valid && ((!axil_read_valid) || S_AXI_RREADY)) ; 
            end
        else
            begin : SIMPLE_READS
                reg axil_arready ; 
                always
                    @(*)
                    axil_arready = (!S_AXI_RVALID) ;
                assign arskd_addr = S_AXI_ARADDR[(C_AXI_ADDR_WIDTH - 1):ADDRLSB] ; 
                assign S_AXI_ARREADY = axil_arready ; 
                assign axil_read_ready = (S_AXI_ARVALID && S_AXI_ARREADY) ; 
            end
    endgenerate
    initial
        axil_read_valid = 1'b0 ;
    always
        @(posedge S_AXI_ACLK)
        if (i_reset) 
            axil_read_valid <=  1'b0 ;
        else
            if (axil_read_ready) 
                axil_read_valid <=  1'b1 ;
            else
                if (S_AXI_RREADY) 
                    axil_read_valid <=  1'b0 ;
    assign S_AXI_RVALID = axil_read_valid ; 
    assign S_AXI_RDATA = axil_read_data ; 
    assign S_AXI_RRESP = 2'b00 ; 
    ////////////////////////////////////////////////////////////////////////
    //
    // Timing Data
    //
    ////////////////////////////////////////////////////////////////////////
    localparam real SYSBUS_CLOCK_PERIOD_NS = (1000.0 / SYSBUS_CLOCK_MHZ) ; 
    //power-up reset time
    localparam integer MEM_TVCS = ((SYSBUS_CLOCK_MHZ * TVCS_10US) * 10) ; 
    ////////////////////////////////////////////////////////////////////////
    //
    // AXI-lite register logic
    //
    ////////////////////////////////////////////////////////////////////////
    // apply_wstrb(old_data, new_data, write_strobes)
    assign wskd_mbar0 = apply_wstrb(mbar0,
                wskd_data,
                wskd_strb) ; 
    assign wskd_mbar1 = apply_wstrb(mbar1,
                wskd_data,
                wskd_strb) ; 
    assign wskd_mcr0 = apply_wstrb(mcr0,
                wskd_data,
                wskd_strb) ; 
    assign wskd_mcr1 = apply_wstrb(mcr1,
                wskd_data,
                wskd_strb) ; 
    assign wskd_mtr = apply_wstrb(mtr,
                wskd_data,
                wskd_strb) ; 
    assign wskd_mtr_ext = apply_wstrb(mtr_ext,
                wskd_data,
                wskd_strb) ; 
    assign wskd_ccr = apply_wstrb(ccr,
                wskd_data,
                wskd_strb) ; 
    assign wskd_dpcr = apply_wstrb(dpcr,
                wskd_data,
                wskd_strb) ; 
    always
        @(posedge S_AXI_ACLK)
        if (i_reset) 
            begin
                mbar0 <=  0 ;
                mbar1 <=  0 ;
                mcr0 <=  0 ;
                mcr1 <=  0 ;
                mtr <=  0 ;
                mtr_ext[31:16] <=  MEM_TVCS ;
                mtr_ext[15:0] <=  0 ;
                ccr <=  0 ;
                dpcr <=  0 ;
            end
        else
            if (axil_write_ready) 
                begin
                    case (awskd_addr[3:0])
                    4'b0001 : 
                        mbar0 <=  wskd_mbar0 ;
                    4'b0010 : 
                        mbar1 <=  wskd_mbar1 ;
                    4'b0011 : 
                        mcr0 <=  {wskd_mcr0[31:6],
                                mcr0_crt,
                                wskd_mcr0[4:0]} ;
                    4'b0100 : 
                        mcr1 <=  {wskd_mcr1[31:6],
                                mcr1_crt,
                                wskd_mcr1[4:0]} ;
                    4'b0101 : 
                        mtr <=  wskd_mtr ;
                    4'b0110 : 
                        mtr_ext <=  wskd_mtr_ext ;
                    4'b0111 : 
                        ccr <=  wskd_ccr ;
                    4'b1000 : 
                        dpcr <=  wskd_dpcr ;
                    endcase 
                end
            else
                begin
                    mcr0[5] <=  mcr0_crt ;
                    mcr1[5] <=  mcr1_crt ;
                end
    always
        @(posedge S_AXI_ACLK)
        if ((OPT_LOWPOWER && (!S_AXI_ARESETN))) 
            axil_read_data <=  0 ;
        else
            if (((!S_AXI_RVALID) || S_AXI_RREADY)) 
                begin
                    case (arskd_addr[3:0])
                    4'b0000 : 
                        axil_read_data <=  csr ;
                    4'b0001 : 
                        axil_read_data <=  {mbar0[31:24],
                                24'b0} ;
                    4'b0010 : 
                        axil_read_data <=  {mbar1[31:24],
                                24'b0} ;
                    4'b0011 : 
                        axil_read_data <=  {mcr0[31],
                                4'b0,
                                mcr0[26:18],
                                12'b0,
                                mcr0[5],
                                mcr0[4],
                                4'b0} ;
                    4'b0100 : 
                        axil_read_data <=  {mcr1[31],
                                4'b0,
                                mcr1[26:18],
                                12'b0,
                                mcr1[5],
                                mcr1[4],
                                4'b0} ;
                    4'b0101 : 
                        axil_read_data <=  {mtr[31:28],
                                mtr[27:24],
                                mtr[23:20],
                                mtr[19:16],
                                mtr[15:12],
                                mtr[11:8],
                                4'b0,
                                mtr[3:0]} ;
                    4'b0110 : 
                        axil_read_data <=  {mtr_ext[31:16],
                                mtr_ext[29:28],
                                mtr_ext[27:26],
                                mtr_ext[25:24],
                                mtr_ext[23:22],
                                mtr_ext[21:20],
                                20'b0} ;
                    4'b0111 : 
                        axil_read_data <=  {ccr[31:30],
                                ccr[29:28],
                                ccr[27],
                                27'b0} ;
                    4'b1000 : 
                        axil_read_data <=  {dpcr[31:24],
                                dpcr[23],
                                dpcr[22],
                                dpcr[21:20],
                                20'b0} ;
                    endcase 
                    if ((OPT_LOWPOWER && (!axil_read_ready))) 
                        axil_read_data <=  0 ;
                end
    function [(C_AXI_DATA_WIDTH - 1):0] apply_wstrb ; 
        input [(C_AXI_DATA_WIDTH - 1):0] prior_data ; 
        input [(C_AXI_DATA_WIDTH - 1):0] new_data ; 
        input [((C_AXI_DATA_WIDTH / 8) - 1):0] wstrb ; 
        integer k ; 
        for (k = 0 ; (k < (C_AXI_DATA_WIDTH / 8)) ; k = (k + 1))
            begin
                apply_wstrb[(k * 8) +: 8] = (wstrb[k] ? new_data[(k * 8) +: 8] : prior_data[(k * 8) +: 8]) ;
            end
    endfunction
    assign csr[31:27] = 5'b0 ; 
    assign csr[26] = csr_wrstoerr ; 
    assign csr[25] = csr_wtrserr ; 
    assign csr[24] = csr_wdecerr ; 
    assign csr[16] = csr_wact ; 
    assign csr[11] = csr_rdsstall ; 
    assign csr[10] = csr_rrstoerr ; 
    assign csr[9] = csr_rtrserr ; 
    assign csr[8] = csr_rdecerr ; 
    assign csr[7] = csr_rsamperr ; 
    assign csr[0] = csr_ract ; 
    assign mbar0_offset = mbar0[31:24] ; 
    assign mcr0_maxen = mcr0[31] ; 
    assign mcr0_maxlen = mcr0[26:18] ; 
    assign mcr0_devtype = mcr0[4] ; 
    assign mbar1_offset = mbar1[31:24] ; 
    assign mcr1_maxen = mcr1[31] ; 
    assign mcr1_maxlen = mcr1[26:18] ; 
    assign mcr1_devtype = mcr1[4] ; 
    assign mtr_rcshi = mtr[31:28] ; 
    assign mtr_wcshi = mtr[27:24] ; 
    assign mtr_rcss = mtr[23:20] ; 
    assign mtr_wcss = mtr[19:16] ; 
    assign mtr_rcsh = mtr[15:12] ; 
    assign mtr_wcsh = mtr[11:8] ; 
    assign mtr_latency = mtr[3:0] ; 
    assign mtr_ext_tvcs = mtr_ext[31:16] ; 
    assign mtr_ext_tdsv = mtr_ext[15:14] ; 
    assign mtr_ext_tdsz = mtr_ext[13:12] ; 
    assign mtr_ext_toz = mtr_ext[11:10] ; 
    assign mtr_ext_tcsm = mtr_ext[9:8] ; 
    assign mtr_ext_trwr = mtr_ext[7:6] ; 
    assign ccr_ram_size = ccr[31:30] ; 
    assign ccr_mode = ccr[29:28] ; 
    assign ccr_dynamic_latency_en = ccr[27] ; 
    assign dpcr_dq_bit_sel = dpcr[31:24] ; 
    assign dpcr_dir = dpcr[23] ; 
    assign dpcr_loadn = dpcr[22] ; 
    assign dpcr_coarse = dpcr[21:20] ; 
endmodule



