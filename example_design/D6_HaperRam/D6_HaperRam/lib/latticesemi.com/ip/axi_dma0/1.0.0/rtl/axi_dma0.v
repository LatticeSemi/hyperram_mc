                    if (ENABLE_UNALIGNED) 
                        begin
                            output_cycle_count_next = (((tr_word_count_next + (addr_reg & OFFSET_MASK)) - 1) >> AXI_BURST_SIZE) ;
                        end
                    else
                        begin
                            output_cycle_count_next = ((tr_word_count_next - 1) >> AXI_BURST_SIZE) ;
