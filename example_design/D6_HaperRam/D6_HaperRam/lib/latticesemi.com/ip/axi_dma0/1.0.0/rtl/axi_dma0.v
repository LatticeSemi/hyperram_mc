                        end
                    else
                        begin
                            state_next = STATE_IDLE ;
                        end
                end
            STATE_START : 
                begin
                    // start state - initiate new AXI transfer
                    if (((op_word_count_reg <= (AXI_MAX_BURST_SIZE - (addr_reg & OFFSET_MASK))) || (AXI_MAX_BURST_SIZE >= 4096))) 
                        begin
                            // packet smaller than max burst size
                            if ((((((addr_reg & 12'hfff) + (op_word_count_reg & 12'hfff)) >> 12) != 0) || ((op_word_count_reg >> 12) != 0))) 
                                begin
                                    // crosses 4k boundary
                                    tr_word_count_next = (13'h1000 - (addr_reg & 12'hfff)) ;
                                end
                            else
                                begin
                                    // does not cross 4k boundary
                                    tr_word_count_next = op_word_count_reg ;
                                end
                        end
                    else
                        begin
                            // packet larger than max burst size
                            if (((((addr_reg & 12'hfff) + AXI_MAX_BURST_SIZE) >> 12) != 0)) 
                                begin
                                    // crosses 4k boundary
                                    tr_word_count_next = (13'h1000 - (addr_reg & 12'hfff)) ;
                                end
                            else
                                begin
                                    // does not cross 4k boundary
                                    tr_word_count_next = (AXI_MAX_BURST_SIZE - (addr_reg & OFFSET_MASK)) ;
                                end
                        end
