                                            begin
                                                // current AXI transfer complete, but there is more data to transfer
                                                // enqueue status FIFO entry for write completion
                                                status_fifo_we = 1'b1 ;
                                                status_fifo_wr_len = length_next ;
                                                status_fifo_wr_tag = tag_reg ;
                                                status_fifo_wr_id = axis_id_next ;
                                                status_fifo_wr_dest = axis_dest_next ;
                                                status_fifo_wr_user = axis_user_next ;
                                                status_fifo_wr_last = 1'b0 ;
                                                s_axis_write_data_tready_next = 1'b0 ;
                                                state_next = STATE_START ;
                                            end
                                        else
                                            begin
                                                // no more data to transfer, finish operation
                                                if ((last_cycle_offset_reg > 0)) 
                                                    begin
                                                        m_axi_wstrb_int = (strb_offset_mask_reg & ({AXI_STRB_WIDTH{1'b1}} >> (AXI_STRB_WIDTH - last_cycle_offset_reg))) ;
                                                        if (first_cycle_reg) 
                                                            begin
                                                                length_next = (length_reg + (last_cycle_offset_reg - offset_reg)) ;
                                                            end
                                                        else
                                                            begin
                                                                length_next = (length_reg + last_cycle_offset_reg) ;
                                                            end
                                                    end
                                                // enqueue status FIFO entry for write completion
                                                status_fifo_we = 1'b1 ;
                                                status_fifo_wr_len = length_next ;
                                                status_fifo_wr_tag = tag_reg ;
                                                status_fifo_wr_id = axis_id_next ;
                                                status_fifo_wr_dest = axis_dest_next ;
                                                status_fifo_wr_user = axis_user_next ;
                                                status_fifo_wr_last = 1'b1 ;
                                                if (AXIS_LAST_ENABLE) 
                                                    begin
                                                        // not at the end of packet; drop remainder
                                                        s_axis_write_data_tready_next = shift_axis_input_tready ;
                                                        state_next = STATE_DROP_DATA ;
                                                    end
                                                else
                                                    begin
                                                        // no framing; return to idle
                                                        s_axis_write_data_tready_next = 1'b0 ;
                                                        s_axis_write_desc_ready_next = (enable && active_count_av_reg) ;
                                                        state_next = STATE_IDLE ;
                                                    end
                                            end
                                    end
                                else
                                    begin
                                        s_axis_write_data_tready_next = ((m_axi_wready_int && (last_transfer_reg || input_active_next)) && shift_axis_input_tready) ;
                                        state_next = STATE_WRITE ;
                                    end
                        end
                    else
                        begin
                            state_next = STATE_WRITE ;
                        end
                end
            STATE_FINISH_BURST : 
                begin
                    // finish current AXI burst
                    if (m_axi_wready_int) 
                        begin
                            // update counters
                            if (input_active_reg) 
                                begin
                                    input_cycle_count_next = (input_cycle_count_reg - 1) ;
                                    input_active_next = (input_cycle_count_reg > 0) ;
                                end
                            input_last_cycle_next = (input_cycle_count_next == 0) ;
                            output_cycle_count_next = (output_cycle_count_reg - 1) ;
                            output_last_cycle_next = (output_cycle_count_next == 0) ;
                            m_axi_wdata_int = {AXI_DATA_WIDTH{1'b0}} ;
                            m_axi_wstrb_int = {AXI_STRB_WIDTH{1'b0}} ;
                            m_axi_wvalid_int = 1'b1 ;
                            if (output_last_cycle_reg) 
                                begin
                                    // no more data to transfer, finish operation
                                    m_axi_wlast_int = 1'b1 ;
                                    s_axis_write_data_tready_next = 1'b0 ;
                                    s_axis_write_desc_ready_next = (enable && active_count_av_reg) ;
                                    state_next = STATE_IDLE ;
                                end
                            else
                                begin
                                    // more cycles in AXI transfer
                                    state_next = STATE_FINISH_BURST ;
                                end
                        end
                    else
                        begin
                            state_next = STATE_FINISH_BURST ;
                        end
                end
            STATE_DROP_DATA : 
                begin
                    // drop excess AXI stream data
                    s_axis_write_data_tready_next = shift_axis_input_tready ;
                    if (shift_axis_tvalid) 
                        begin
                            if ((s_axis_write_data_tready && s_axis_write_data_tvalid)) 
                                begin
                                    transfer_in_save = 1'b1 ;
                                end
                            if (shift_axis_tlast) 
                                begin
                                    s_axis_write_data_tready_next = 1'b0 ;
                                    s_axis_write_desc_ready_next = (enable && active_count_av_reg) ;
                                    state_next = STATE_IDLE ;
                                end
                            else
                                begin
                                    state_next = STATE_DROP_DATA ;
                                end
                        end
                    else
                        begin
                            state_next = STATE_DROP_DATA ;
                        end
                end
            endcase 
            if ((status_fifo_rd_ptr_reg != status_fifo_wr_ptr_reg)) 
                begin
                    // status FIFO not empty
                    if ((m_axi_bready && m_axi_bvalid)) 
                        begin
                            // got write completion, pop and return status
                            m_axis_write_desc_status_len_next = status_fifo_len[status_fifo_rd_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] ;
                            m_axis_write_desc_status_tag_next = status_fifo_tag[status_fifo_rd_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] ;
                            m_axis_write_desc_status_id_next = status_fifo_id[status_fifo_rd_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] ;
                            m_axis_write_desc_status_dest_next = status_fifo_dest[status_fifo_rd_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] ;
                            m_axis_write_desc_status_user_next = status_fifo_user[status_fifo_rd_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] ;
                            if ((bresp_next == AXI_RESP_SLVERR)) 
                                begin
                                    m_axis_write_desc_status_error_next = DMA_ERROR_AXI_WR_SLVERR ;
                                end
                            else
                                if ((bresp_next == AXI_RESP_DECERR)) 
                                    begin
                                        m_axis_write_desc_status_error_next = DMA_ERROR_AXI_WR_DECERR ;
                                    end
                                else
                                    begin
                                        m_axis_write_desc_status_error_next = DMA_ERROR_NONE ;
                                    end
                            m_axis_write_desc_status_valid_next = status_fifo_last[status_fifo_rd_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] ;
                            status_fifo_rd_ptr_next = (status_fifo_rd_ptr_reg + 1) ;
                            m_axi_bready_next = 1'b0 ;
                            if (status_fifo_last[status_fifo_rd_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]]) 
                                begin
                                    bresp_next = AXI_RESP_OKAY ;
                                end
                            dec_active = 1'b1 ;
                        end
                    else
                        begin
                            // wait for write completion
                            m_axi_bready_next = 1'b1 ;
                        end
                end
        end
    always
        @(posedge clk)
        begin
            state_reg <=  state_next ;
            s_axis_write_desc_ready_reg <=  s_axis_write_desc_ready_next ;
            m_axis_write_desc_status_len_reg <=  m_axis_write_desc_status_len_next ;
            m_axis_write_desc_status_tag_reg <=  m_axis_write_desc_status_tag_next ;
            m_axis_write_desc_status_id_reg <=  m_axis_write_desc_status_id_next ;
            m_axis_write_desc_status_dest_reg <=  m_axis_write_desc_status_dest_next ;
            m_axis_write_desc_status_user_reg <=  m_axis_write_desc_status_user_next ;
            m_axis_write_desc_status_error_reg <=  m_axis_write_desc_status_error_next ;
            m_axis_write_desc_status_valid_reg <=  m_axis_write_desc_status_valid_next ;
            s_axis_write_data_tready_reg <=  s_axis_write_data_tready_next ;
            m_axi_awaddr_reg <=  m_axi_awaddr_next ;
            m_axi_awlen_reg <=  m_axi_awlen_next ;
            m_axi_awvalid_reg <=  m_axi_awvalid_next ;
            m_axi_bready_reg <=  m_axi_bready_next ;
            addr_reg <=  addr_next ;
            offset_reg <=  offset_next ;
            strb_offset_mask_reg <=  strb_offset_mask_next ;
            zero_offset_reg <=  zero_offset_next ;
            last_cycle_offset_reg <=  last_cycle_offset_next ;
            length_reg <=  length_next ;
            op_word_count_reg <=  op_word_count_next ;
            tr_word_count_reg <=  tr_word_count_next ;
            input_cycle_count_reg <=  input_cycle_count_next ;
            output_cycle_count_reg <=  output_cycle_count_next ;
            input_active_reg <=  input_active_next ;
            first_cycle_reg <=  first_cycle_next ;
            input_last_cycle_reg <=  input_last_cycle_next ;
            output_last_cycle_reg <=  output_last_cycle_next ;
            last_transfer_reg <=  last_transfer_next ;
            bresp_reg <=  bresp_next ;
            tag_reg <=  tag_next ;
            axis_id_reg <=  axis_id_next ;
            axis_dest_reg <=  axis_dest_next ;
            axis_user_reg <=  axis_user_next ;
            // datapath
            if (flush_save) 
                begin
                    save_axis_tkeep_reg <=  {AXIS_KEEP_WIDTH_INT{1'b0}} ;
                    save_axis_tlast_reg <=  1'b0 ;
                    shift_axis_extra_cycle_reg <=  1'b0 ;
                end
            else
                if (transfer_in_save) 
                    begin
                        save_axis_tdata_reg <=  s_axis_write_data_tdata ;
                        save_axis_tkeep_reg <=  (AXIS_KEEP_ENABLE ? s_axis_write_data_tkeep : {AXIS_KEEP_WIDTH_INT{1'b1}}) ;
                        save_axis_tlast_reg <=  s_axis_write_data_tlast ;
                        shift_axis_extra_cycle_reg <=  (s_axis_write_data_tlast & ((s_axis_write_data_tkeep >> (AXIS_KEEP_WIDTH_INT - offset_reg)) != 0)) ;
                    end
            if (status_fifo_we) 
                begin
                    status_fifo_len[status_fifo_wr_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] <=  status_fifo_wr_len ;
                    status_fifo_tag[status_fifo_wr_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] <=  status_fifo_wr_tag ;
                    status_fifo_id[status_fifo_wr_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] <=  status_fifo_wr_id ;
                    status_fifo_dest[status_fifo_wr_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] <=  status_fifo_wr_dest ;
                    status_fifo_user[status_fifo_wr_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] <=  status_fifo_wr_user ;
                    status_fifo_last[status_fifo_wr_ptr_reg[(STATUS_FIFO_ADDR_WIDTH - 1):0]] <=  status_fifo_wr_last ;
                    status_fifo_wr_ptr_reg <=  (status_fifo_wr_ptr_reg + 1) ;
                end
            status_fifo_rd_ptr_reg <=  status_fifo_rd_ptr_next ;
            if ((((active_count_reg < (2 ** STATUS_FIFO_ADDR_WIDTH)) && inc_active) && (!dec_active))) 
                begin
                    active_count_reg <=  (active_count_reg + 1) ;
                    active_count_av_reg <=  (active_count_reg < ((2 ** STATUS_FIFO_ADDR_WIDTH) - 1)) ;
                end
            else
                if ((((active_count_reg > 0) && (!inc_active)) && dec_active)) 
                    begin
                        active_count_reg <=  (active_count_reg - 1) ;
                        active_count_av_reg <=  1'b1 ;
                    end
                else
                    begin
                        active_count_av_reg <=  (active_count_reg < (2 ** STATUS_FIFO_ADDR_WIDTH)) ;
                    end
            if (rst) 
                begin
                    state_reg <=  STATE_IDLE ;
                    s_axis_write_desc_ready_reg <=  1'b0 ;
                    m_axis_write_desc_status_valid_reg <=  1'b0 ;
                    s_axis_write_data_tready_reg <=  1'b0 ;
                    m_axi_awvalid_reg <=  1'b0 ;
                    m_axi_bready_reg <=  1'b0 ;
                    bresp_reg <=  AXI_RESP_OKAY ;
                    save_axis_tlast_reg <=  1'b0 ;
                    shift_axis_extra_cycle_reg <=  1'b0 ;
                    status_fifo_wr_ptr_reg <=  0 ;
                    status_fifo_rd_ptr_reg <=  0 ;
                    active_count_reg <=  0 ;
                    active_count_av_reg <=  1'b1 ;
                end
        end
    // output datapath logic
    reg [(AXI_DATA_WIDTH - 1):0] m_axi_wdata_reg = {AXI_DATA_WIDTH{1'b0}} ; 
    reg [(AXI_STRB_WIDTH - 1):0] m_axi_wstrb_reg = {AXI_STRB_WIDTH{1'b0}} ; 
    reg m_axi_wlast_reg = 1'b0 ; 
    reg m_axi_wvalid_reg = 1'b0 ; 
    reg [((OUTPUT_FIFO_ADDR_WIDTH + 1) - 1):0] out_fifo_wr_ptr_reg = 0 ; 
    reg [((OUTPUT_FIFO_ADDR_WIDTH + 1) - 1):0] out_fifo_rd_ptr_reg = 0 ; 
    reg out_fifo_half_full_reg = 1'b0 ; 
    wire out_fifo_full = (out_fifo_wr_ptr_reg == (out_fifo_rd_ptr_reg ^ {1'b1,
                {OUTPUT_FIFO_ADDR_WIDTH{1'b0}}})) ; 
    wire out_fifo_empty = (out_fifo_wr_ptr_reg == out_fifo_rd_ptr_reg) ; 
    (* ram_style="distributed", ramstyle="no_rw_check, mlab" *) reg [(AXI_DATA_WIDTH - 1):0] out_fifo_wdata [((2 ** OUTPUT_FIFO_ADDR_WIDTH) - 1):0] ; 
    (* ram_style="distributed", ramstyle="no_rw_check, mlab" *) reg [(AXI_STRB_WIDTH - 1):0] out_fifo_wstrb [((2 ** OUTPUT_FIFO_ADDR_WIDTH) - 1):0] ; 
    (* ram_style="distributed", ramstyle="no_rw_check, mlab" *) reg out_fifo_wlast [((2 ** OUTPUT_FIFO_ADDR_WIDTH) - 1):0] ; 
    assign m_axi_wready_int = (!out_fifo_half_full_reg) ; 
    assign m_axi_wdata = m_axi_wdata_reg ; 
    assign m_axi_wstrb = m_axi_wstrb_reg ; 
    assign m_axi_wvalid = m_axi_wvalid_reg ; 
    assign m_axi_wlast = m_axi_wlast_reg ; 
    always
        @(posedge clk)
        begin
            m_axi_wvalid_reg <=  (m_axi_wvalid_reg && (!m_axi_wready)) ;
            out_fifo_half_full_reg <=  ($unsigned((out_fifo_wr_ptr_reg - out_fifo_rd_ptr_reg)) >= (2 ** (OUTPUT_FIFO_ADDR_WIDTH - 1))) ;
            if (((!out_fifo_full) && m_axi_wvalid_int)) 
                begin
                    out_fifo_wdata[out_fifo_wr_ptr_reg[(OUTPUT_FIFO_ADDR_WIDTH - 1):0]] <=  m_axi_wdata_int ;
                    out_fifo_wstrb[out_fifo_wr_ptr_reg[(OUTPUT_FIFO_ADDR_WIDTH - 1):0]] <=  m_axi_wstrb_int ;
                    out_fifo_wlast[out_fifo_wr_ptr_reg[(OUTPUT_FIFO_ADDR_WIDTH - 1):0]] <=  m_axi_wlast_int ;
                    out_fifo_wr_ptr_reg <=  (out_fifo_wr_ptr_reg + 1) ;
                end
            if (((!out_fifo_empty) && ((!m_axi_wvalid_reg) || m_axi_wready))) 
                begin
                    m_axi_wdata_reg <=  out_fifo_wdata[out_fifo_rd_ptr_reg[(OUTPUT_FIFO_ADDR_WIDTH - 1):0]] ;
                    m_axi_wstrb_reg <=  out_fifo_wstrb[out_fifo_rd_ptr_reg[(OUTPUT_FIFO_ADDR_WIDTH - 1):0]] ;
                    m_axi_wlast_reg <=  out_fifo_wlast[out_fifo_rd_ptr_reg[(OUTPUT_FIFO_ADDR_WIDTH - 1):0]] ;
                    m_axi_wvalid_reg <=  1'b1 ;
                    out_fifo_rd_ptr_reg <=  (out_fifo_rd_ptr_reg + 1) ;
                end
            if (rst) 
                begin
                    out_fifo_wr_ptr_reg <=  0 ;
                    out_fifo_rd_ptr_reg <=  0 ;
                    m_axi_wvalid_reg <=  1'b0 ;
                end
        end
endmodule



